Firstnumber = int(input())
Secondnumber = int(input())
inputoperation = input()
if inputoperation == "+":
    print(Firstnumber + Secondnumber)
elif inputoperation == "-":
    print(Firstnumber - Secondnumber)
elif inputoperation == "*":
    print(Firstnumber * Secondnumber)
elif inputoperation == "/":
    print(Firstnumber / Secondnumber)